/**
 * KAR-19.5 AC4 / EPIC-19-S34 — **a test that cannot go red is worse than no
 * test**, so every link is cut in turn and the smoke test must fail for each.
 *
 * This is the part of the story that matters. A smoke test is a claim about
 * wiring, and the only way to settle a claim about wiring is to unplug
 * something and watch it break. Without this table, KAR-19.5 would be the
 * 2026-08-12 mistake reproduced exactly one level up: a green assertion nobody
 * had ever seen fail.
 *
 * **How a link is cut.** The scenario runs the built binary, so a row copies
 * `packages/cli/dist` and applies exactly one textual edit to the copy — the
 * bundler preserves identifiers and comments, so a call site is a stable
 * anchor. Two properties make that a cut rather than a mutation:
 *
 * - The `find` string must occur **exactly once** across the whole copied
 *   bundle. Zero occurrences means the row's anchor has rotted and the row
 *   fails; two means the edit is ambiguous and the row fails. Either way the
 *   table refuses to report a pass it cannot justify.
 * - The row is checked against the **unsabotaged** binary once, at the top,
 *   by `live-run.test.ts` itself — if the intact chain did not reach a terminal
 *   state, every row below would fail for that reason instead of its own.
 *
 * **The failure must name the link.** S34's last clause — *"it does not fail
 * with a timeout alone"* — is why `runSmokeScenario` waits for each stage by
 * name and throws `SmokeStageMissing` carrying the link. A row asserts both
 * that the scenario failed *and* which link it named, so a cut that broke
 * something else entirely is a red row rather than a quiet pass.
 *
 * Verifies: EPIC-19-S34 · KAR-19.5 AC4 · test plan #2
 */
import { cpSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { mkdtemp, rm } from 'node:fs/promises';
import { join } from 'node:path';
import { afterEach, beforeAll, expect, it, describe as suite } from 'vitest';
import {
  DIST_DIR,
  ensureBuilt,
  LINKS,
  repoRoot,
  runSmokeScenario,
  type SmokeLink,
  SmokeStageMissing,
  SMOKE_STAGE_TIMED_OUT as TIMED_OUT,
} from './support/harness.ts';

beforeAll(() => {
  ensureBuilt();
}, 600_000);

const copies: string[] = [];

/**
 * Always removed, `DeFlow_KEEP_TMP` or not — unlike the scenario's own tmpdir.
 *
 * AC7's keep is for the thing a failure is diagnosed from: the run's data
 * directory, with a ledger you open in `sqlite3`. A sabotaged bundle is not
 * that. It is 6 MB of generated bytes, reproducible exactly from `dist/` plus
 * the row's own `find`/`replace`, and keeping it would leave a near-identical
 * copy of the real binary sitting beside it in the working tree — which CI does
 * set `DeFlow_KEEP_TMP=1` for the whole job, so the exception would be the
 * normal case there rather than the rare one.
 */
afterEach(async () => {
  for (const dir of copies.splice(0)) await rm(dir, { recursive: true, force: true });
});

/** One textual edit. `find` must occur exactly once in the whole bundle. */
interface Cut {
  readonly find: string;
  readonly replace: string;
}

interface Sabotage {
  /** S34's own wording for the link this row removes. */
  readonly row: string;
  /**
   * Every call site that produces this link.
   *
   * Usually one. `the framing wake written at intake` has two, and that is a
   * finding rather than an inconvenience: KAR-19.1 added `rearmFraming`, which
   * re-arms a missing framing wake once a second for any run that is pending
   * framing and has no row. So intake's own `scheduleWake` is **repaired within
   * a tick** if it is removed alone, and a row that cut only it would report a
   * hole in the smoke test that is really a redundancy in the daemon. Cutting a
   * link means cutting the link, not one of its two producers.
   */
  readonly cuts: readonly Cut[];
  /** The stage the smoke test must then name. */
  readonly names: SmokeLink;
  /**
   * KAR-19.9 AC9 — substrings the failure message must also carry.
   *
   * Every row above cuts a link, and the link's *name* is the whole diagnosis:
   * the stage never happened, and which stage it was says why. The row this
   * field exists for is different in kind — nothing is missing, a provider is
   * **failing** — and for that one "the run did not reach `run.created`" is a
   * true sentence that sends the next reader to exactly the wrong place. So
   * that row asserts the ending as well as the link: the run *failed*, and it
   * failed for a reason out of KAR-02.10's closed taxonomy.
   */
  readonly says?: readonly string[];
  /**
   * KAR-19.9 AC9 — *"it does not reach its own timeout"*.
   *
   * A row that fails by waiting out the stage budget tells the next reader
   * nothing about which link broke, which AC4 already calls a hole. This is the
   * inverse clause, and it is the whole point of the row: before this story the
   * failing turn was re-dispatched every 30 s with no ceiling, so the scenario
   * sat here until the budget expired and reported that time had passed.
   *
   * Asserted against the **sentence** rather than against a wall-clock bound,
   * and that is the stronger of the two rather than the cheaper. `stage()` has
   * exactly one arm that gives up on the clock and it says so in words, so its
   * absence is the fact this clause is about, stated exactly. A bound on
   * elapsed time would be measuring a scenario that also runs `DeFlow init`,
   * two `git` invocations and a cold daemon start, and would read a loaded
   * machine as a reintroduced infinite retry.
   */
  readonly notByTimeout?: boolean;
}

