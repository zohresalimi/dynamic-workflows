/** The bundle chunks a sabotage may be applied to. */
const chunksOf = (dir: string): readonly string[] =>
  readdirSync(dir, { withFileTypes: true })
    .filter((entry) => entry.isFile() && entry.name.endsWith('.mjs'))
    .map((entry) => join(dir, entry.name));

/**
 * `dist/` with one link cut, and a refusal when the cut did not apply cleanly.
 *
 * The occurrence count is the row's own integrity check: an anchor that has
 * rotted since it was written would otherwise produce a *green* row — the
 * scenario passing because nothing was actually removed — which is the exact
 * shape of hole this table exists to close.
 */
async function sabotagedDist(row: Sabotage): Promise<string> {
  // Beside `packages/cli/dist` rather than in `os.tmpdir()`, and it is not a
  // preference: the bundle leaves its native dependencies external
  // (better-sqlite3, node-pty), and Node resolves those by walking up to a
  // `node_modules` that has them — which in a pnpm workspace is
  // `packages/cli/node_modules`, not the repository root's. A copy anywhere
  // else exits 1 on `ERR_MODULE_NOT_FOUND` at `DeFlow init`, and every row
  // below would then fail for that reason instead of for the link it cut.
  // `.gitignore` covers the prefix.
  const dir = await mkdtemp(join(repoRoot, 'packages', 'cli', '.smoke-sabotage-'));
  copies.push(dir);
  cpSync(DIST_DIR, dir, { recursive: true });

  for (const cut of row.cuts) {
    let applied = 0;
    for (const chunk of chunksOf(dir)) {
      const source = readFileSync(chunk, 'utf8');
      const occurrences = source.split(cut.find).length - 1;
      if (occurrences === 0) continue;
      applied += occurrences;
      writeFileSync(chunk, source.split(cut.find).join(cut.replace), 'utf8');
    }
    expect(
      applied,
      `the sabotage for "${row.row}" matched ${String(applied)} times in the bundle for ` +
        `${JSON.stringify(cut.find.slice(0, 60))}; it must match exactly once, or the row is ` +
        'asserting nothing about the link it names',
    ).toBe(1);
  }
  return dir;
}

suite('EPIC-19-S34 — every link cut in turn, and the smoke test goes red for each', () => {
  for (const row of TABLE) {
    it(`fails, naming the link, with ${row.row} removed`, { timeout: 180_000 }, async () => {
      const distDir = await sabotagedDist(row);

      // The scenario, against the cut bundle. A stage budget far below the
      // smoke test's own: a cut link is a stage that will never happen, and
      // six rows waiting out the full budget would cost ten minutes to learn
      // nothing.
      const budgetMs = 20_000;
      const began = Date.now();
      const thrown = await runSmokeScenario({ distDir, stageTimeoutMs: budgetMs }).then(
        () => null,
        (error: unknown) => error,
      );
      const tookMs = Date.now() - began;

      expect(
        thrown,
        `the smoke test passed with ${row.row} removed from the shipped path, which means it ` +
          'does not actually assert that link',
      ).not.toBeNull();
      expect(thrown).toBeInstanceOf(SmokeStageMissing);
      expect((thrown as SmokeStageMissing).link).toBe(row.names);
      // S34's last clause: the message names the link rather than only
      // reporting that time ran out.
      const message = (thrown as SmokeStageMissing).message;
      expect(message).toContain(row.names);

      // KAR-19.9 AC9 / EPIC-19-S64 — and, for the row whose provider fails
      // rather than whose link is missing, what the run's own ledger says
      // about the ending.
      for (const phrase of row.says ?? []) expect(message, message).toContain(phrase);

      if (row.notByTimeout === true) {
        expect(
          message,
          `the row for "${row.row}" gave up on the clock after ${String(tookMs)} ms of a ` +
            `${String(budgetMs)} ms stage budget, which is a timeout wearing a failure’s ` +
            'clothes: a run that gave up must end the scenario, not outlast it',
        ).not.toContain(TIMED_OUT);
      }
    });
  }
});
